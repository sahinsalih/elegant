let currentLocale = 'tr';

function setLocale(locale) {
  currentLocale = locale === 'en' ? 'en' : 'tr';
  document.documentElement.lang = currentLocale === 'en' ? 'en' : 'tr';
}

function getLocale() {
  return currentLocale;
}

function t(key, vars) {
  const pack = STR[currentLocale] || STR.tr;
  let text = pack[key] ?? STR.tr[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

function applyChrome() {
  document.querySelectorAll('[data-i18n]').forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((node) => {
    node.setAttribute('aria-label', t(node.dataset.i18nAria));
  });
  document.querySelectorAll('[data-i18n-title]').forEach((node) => {
    const label = t(node.dataset.i18nTitle);
    node.title = label;
    if (!node.hasAttribute('data-i18n-aria')) node.setAttribute('aria-label', label);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
    node.placeholder = t(node.dataset.i18nPlaceholder);
  });
}
